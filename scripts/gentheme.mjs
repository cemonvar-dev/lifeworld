// Generates styling/theme.css. Run from the repo root: node scripts/gentheme.mjs
import { writeFileSync } from 'node:fs';
const D = 'html[data-theme="dusk"]';
const esc = c => c.replace(/\//g, '\\/').replace(/:/g, '\\:').replace(/\./g, '\\.');
const rules = [];
const add = (sel, body) => rules.push(`${sel}{${body}}`);
// Neutral surfaces
const S = { surface: '49,45,74', s2: '54,49,79', s3: '62,56,89', s4: '70,63,102', s5: '82,74,117' };
const bgMap = { 'bg-white': S.surface, 'bg-slate-50': S.s2, 'bg-slate-100': S.s3, 'bg-slate-200': S.s4, 'bg-slate-300': S.s5, 'bg-gray-50': S.s2, 'bg-gray-100': S.s3, 'bg-gray-200': S.s4 };
for (const [c, rgb] of Object.entries(bgMap)) {
	add(`${D} .${esc(c)}`, `background-color:rgb(${rgb})`);
	for (const a of [95, 90, 85, 80, 75, 70, 60, 50, 40]) add(`${D} .${esc(c + '/' + a)}`, `background-color:rgba(${rgb},${a / 100})`);
	add(`${D} .${esc('hover:' + c)}:hover`, `background-color:rgb(${rgb === S.surface ? S.s3 : S.s5})`);
	for (const a of [80, 60]) add(`${D} .${esc('hover:' + c + '/' + a)}:hover`, `background-color:rgba(${S.s3},${a / 100})`);
	add(`${D} .${esc('active:' + c)}:active`, `background-color:rgb(${S.s5})`);
}
// Neutral text
const ink = { 900: '#eeebfa', 800: '#eeebfa', 700: '#e2def3', 600: '#c6c0e0', 500: '#aaa4c8', 400: '#9089b2', 300: '#766f98', 200: '#5f5880' };
for (const fam of ['slate', 'gray']) for (const [n, v] of Object.entries(ink)) {
	add(`${D} .${esc(`text-${fam}-${n}`)}`, `color:${v}`);
	add(`${D} .${esc(`hover:text-${fam}-${n}`)}:hover`, `color:${v}`);
	add(`${D} .${esc(`placeholder:text-${fam}-${n}`)}::placeholder`, `color:${v}`);
}
// Neutral borders / rings
for (const c of ['border-slate-100', 'border-slate-200', 'border-slate-300', 'border-gray-200', 'border-gray-300', 'border-white', 'border-white/60', 'border-white/70', 'border-slate-200/80', 'border-slate-200/70', 'border-slate-200/60', 'border-slate-100/80', 'border-t', 'border-b'])
	add(`${D} .${esc(c)}`, 'border-color:#474066');
for (const c of ['ring-slate-100', 'ring-slate-200', 'ring-slate-300', 'ring-white', 'ring-black/5', 'ring-slate-900/5']) add(`${D} .${esc(c)}`, '--tw-ring-color:#474066');
add(`${D} .border`, 'border-color:#474066');
// Pastel hues → translucent tints with light text
const H = {
	blue: ['96,165,250', '#93c5fd'], indigo: ['129,140,248', '#a5b4fc'], violet: ['167,139,250', '#c4b5fd'], purple: ['192,132,252', '#d8b4fe'],
	fuchsia: ['232,121,249', '#f0abfc'], pink: ['244,114,182', '#f9a8d4'], rose: ['251,113,133', '#fda4af'], red: ['248,113,113', '#fca5a5'],
	orange: ['251,146,60', '#fdba74'], amber: ['251,191,36', '#fcd34d'], yellow: ['250,204,21', '#fde047'], lime: ['163,230,53', '#bef264'],
	green: ['74,222,128', '#86efac'], emerald: ['52,211,153', '#6ee7b7'], teal: ['45,212,191', '#5eead4'], cyan: ['34,211,238', '#67e8f9'], sky: ['56,189,248', '#7dd3fc'],
};
for (const [h, [rgb, light]] of Object.entries(H)) {
	const a = { 50: .13, 100: .18, 200: .26 };
	for (const [n, al] of Object.entries(a)) {
		add(`${D} .${esc(`bg-${h}-${n}`)}`, `background-color:rgba(${rgb},${al})`);
		add(`${D} .${esc(`hover:bg-${h}-${n}`)}:hover`, `background-color:rgba(${rgb},${(al + .08).toFixed(2)})`);
		for (const o of [50, 60, 70, 80]) add(`${D} .${esc(`bg-${h}-${n}/${o}`)}`, `background-color:rgba(${rgb},${(al * o / 100).toFixed(3)})`);
	}
	for (const n of [100, 200, 300, 400]) {
		add(`${D} .${esc(`border-${h}-${n}`)}`, `border-color:rgba(${rgb},.38)`);
		add(`${D} .${esc(`ring-${h}-${n}`)}`, `--tw-ring-color:rgba(${rgb},.4)`);
		add(`${D} .${esc(`hover:border-${h}-${n}`)}:hover`, `border-color:rgba(${rgb},.5)`);
		add(`${D} .${esc(`hover:ring-${h}-${n}`)}:hover`, `--tw-ring-color:rgba(${rgb},.5)`);
	}
	for (const n of [500, 600, 700, 800, 900]) {
		add(`${D} .${esc(`text-${h}-${n}`)}`, `color:${light}`);
		add(`${D} .${esc(`hover:text-${h}-${n}`)}:hover`, `color:${light}`);
	}
}
